#!/usr/bin/env bash

# Прерывать выполнение скрипта, если любая из команд завершилась ошибкой
set -e

# Определение абсолютного пути к директории, где лежит сам скрипт
# Это защищает от сбоев, когда cron запускает скрипт из другой папки
BASE_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
cd "$BASE_DIR"

# Настройки папок (относительно корня проекта)
URLS_DIR="urls"
DATA_DIR="scrapped_data"

# Название лог-файла для вывода дат (для удобства отладки в cron)
echo "=== [$(date '+%Y-%m-%d %H:%M:%S')] СТАРТ ПОЛНОГО ЦИКЛА ОБНОВЛЕНИЯ ==="

# -----------------------------------------------------------------------------
# Шаг 0: Активация виртуального окружения (если оно есть)
# -----------------------------------------------------------------------------
if [ -d ".venv" ]; then
    echo "Активация виртуального окружения .venv..."
    source .venv/bin/activate
fi

# -----------------------------------------------------------------------------
# Шаг 1: Запуск Collector
# -----------------------------------------------------------------------------
echo "Шаг 1: Запуск сборщика данных (Collector)..."
python3 collector.py \
    --urls-dir "$URLS_DIR" \
    --output-dir "$DATA_DIR" \
    --vk

# -----------------------------------------------------------------------------
# Шаг 2: Поиск созданного файла и запуск Updater
# -----------------------------------------------------------------------------
echo "Шаг 2: Поиск самого свежего файла с дампами..."

# Ищем самый свежий файл по дате изменения в папке scrapped_data
LATEST_FILE=$(ls -t "$DATA_DIR"/scrapped_*.jsonl 2>/dev/null | head -n 1)

if [ -z "$LATEST_FILE" ]; then
    echo "Ошибка: Созданный файл scrapped_*.jsonl не найден в папе $DATA_DIR!"
    exit 1
fi

echo "Найден файл для импорта: $LATEST_FILE"
echo "Запуск пайплайна обновления базы данных (Updater)..."

python3 updater.py --file "$LATEST_FILE"

# -----------------------------------------------------------------------------
# Шаг 3: Безопасное удаление временного файла
# -----------------------------------------------------------------------------
echo "Шаг 3: Очистка временных файлов..."
if [ -f "$LATEST_FILE" ]; then
    rm "$LATEST_FILE"
    echo "Временный файл $LATEST_FILE успешно удален."
else
    echo "Предупреждение: Файл $LATEST_FILE исчез до этапа удаления."
fi

echo "[$(date '+%Y-%m-%d %H:%M:%S')] Пайплайн успешно завершил работу!"